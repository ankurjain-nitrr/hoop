import { itemLines, type ReviewDoc } from "./contract.js";

export type LineRef = { item: string; line: number };

/**
 * Renders a review document as markdown for reading and line comments on GitHub. Every item line
 * starts with its ID, and `lineMap[n]` gives the item and item line at markdown line n (1-based),
 * so a comment on the markdown maps back to the contract. Same input, same output.
 */
export function renderMarkdown(doc: ReviewDoc, revision: number): { markdown: string; lineMap: Record<number, LineRef> } {
  const out: string[] = [];
  const lineMap: Record<number, LineRef> = {};
  const push = (text: string, ref?: LineRef) => {
    out.push(text);
    if (ref) lineMap[out.length] = ref;
  };
  push(`<!-- Generated by hoop from ${doc.slug}.json (rev ${revision}). Comment on lines; edits to this file are not read. -->`);
  push(`# ${doc.title}`);
  push("");
  push(`> ${doc.tldr.replace(/\n+/g, " ")}`);
  for (const item of doc.items) {
    push("");
    push(`## ${item.id} · ${item.title}`);
    itemLines(item).forEach((text, i) => {
      push("");
      push(`${item.id} · ${text}`, { item: item.id, line: i + 1 });
    });
  }
  push("");
  return { markdown: out.join("\n"), lineMap };
}

/** PR description: TL;DR, then one checkbox per question choice (D9). */
export function renderPrBody(doc: ReviewDoc, revision: number, answers: Record<string, string> = {}): string {
  const out = [
    `**TL;DR:** ${doc.tldr.replace(/\n+/g, " ")}`,
    "",
    `Review \`decisions/${doc.slug}.md\` like code: comment on lines, suggest changes, then approve. Merging this PR approves the decision.`,
  ];
  const questions = doc.items.filter((i) => i.type === "question");
  if (questions.length) {
    out.push("", "### Questions", "", "Tick one option per question.");
    for (const q of questions) {
      out.push("", `**${q.id} · ${q.title}**`, "");
      for (const c of q.choices ?? [])
        out.push(`- [${answers[q.id] === c.id ? "x" : " "}] \`${q.id}:${c.id}\` ${c.label}${c.recommended ? " _(recommended)_" : ""}`);
    }
  }
  out.push("", `<!-- hoop:${doc.slug} rev ${revision} -->`);
  return out.join("\n");
}

/** Reads ticked `- [x] \`Q-1:b\`` checkboxes from a PR description. */
export function readCheckboxAnswers(body: string): Record<string, string> {
  const answers: Record<string, string> = {};
  for (const m of body.matchAll(/^- \[[xX]\] `([A-Za-z][A-Za-z0-9-]*):([^`]+)`/gm)) answers[m[1]!] = m[2]!;
  return answers;
}
